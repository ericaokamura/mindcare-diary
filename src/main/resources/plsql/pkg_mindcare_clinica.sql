-- =============================================================================
-- PKG_MINDCARE_CLINICA
-- Indicadores da clínica para o dashboard do administrador: faturamento,
-- receita líquida após comissão, resumo mensal e agenda consolidada.
-- Faturamento considera apenas consultas atendidas e não canceladas, como o
-- ClinicaService. Funções sobrecarregadas aceitam o ID ou o CNPJ da clínica.
-- Depende de: PKG_MINDCARE_COMUM.
-- =============================================================================

CREATE OR REPLACE PACKAGE PKG_MINDCARE_CLINICA AS

    -- Id da clínica pelo CNPJ; erro -20003 se não existir.
    FUNCTION FN_ID_CLINICA (P_CNPJ IN CLINICA.CNPJ%TYPE) RETURN CLINICA.ID%TYPE;

    -- Soma do valor das consultas atendidas no mês.
    FUNCTION FN_FATURAMENTO_MES (
        P_CLINICA_ID IN CLINICA.ID%TYPE,
        P_ANO        IN PLS_INTEGER,
        P_MES        IN PLS_INTEGER
    ) RETURN NUMBER;

    FUNCTION FN_FATURAMENTO_MES (
        P_CNPJ IN CLINICA.CNPJ%TYPE,
        P_ANO  IN PLS_INTEGER,
        P_MES  IN PLS_INTEGER
    ) RETURN NUMBER;

    -- Faturamento do mês descontada a TAXA_COMISSAO da clínica.
    FUNCTION FN_RECEITA_LIQUIDA_MES (
        P_CLINICA_ID IN CLINICA.ID%TYPE,
        P_ANO        IN PLS_INTEGER,
        P_MES        IN PLS_INTEGER
    ) RETURN NUMBER;

    FUNCTION FN_RECEITA_LIQUIDA_MES (
        P_CNPJ IN CLINICA.CNPJ%TYPE,
        P_ANO  IN PLS_INTEGER,
        P_MES  IN PLS_INTEGER
    ) RETURN NUMBER;

    -- Indicadores do mês para o dashboard em uma única chamada.
    PROCEDURE PRC_RESUMO_DASHBOARD (
        P_CLINICA_ID            IN  CLINICA.ID%TYPE,
        P_ANO                   IN  PLS_INTEGER,
        P_MES                   IN  PLS_INTEGER,
        P_TOTAL_PACIENTES       OUT PLS_INTEGER,
        P_TOTAL_PROFISSIONAIS   OUT PLS_INTEGER,
        P_PACIENTES_ATENCAO     OUT PLS_INTEGER,
        P_CONSULTAS_AGENDADAS   OUT PLS_INTEGER,
        P_CONSULTAS_ATENDIDAS   OUT PLS_INTEGER,
        P_CONSULTAS_CANCELADAS  OUT PLS_INTEGER,
        P_TAXA_CANCELAMENTO     OUT NUMBER,
        P_FATURAMENTO           OUT NUMBER,
        P_RECEITA_LIQUIDA       OUT NUMBER
    );

    -- Consultas da clínica no intervalo [P_INICIO, P_FIM] (datas inclusivas), com
    -- nomes de paciente e profissional, ordenadas por data/hora.
    FUNCTION FN_AGENDA_CLINICA (
        P_CLINICA_ID IN CLINICA.ID%TYPE,
        P_INICIO     IN DATE,
        P_FIM        IN DATE
    ) RETURN SYS_REFCURSOR;

END PKG_MINDCARE_CLINICA;
/

CREATE OR REPLACE PACKAGE BODY PKG_MINDCARE_CLINICA AS

    PROCEDURE PRC_VALIDAR_CLINICA (P_CLINICA_ID IN CLINICA.ID%TYPE) IS
        V_EXISTE PLS_INTEGER;
    BEGIN
        SELECT COUNT(*) INTO V_EXISTE FROM CLINICA WHERE ID = P_CLINICA_ID;
        IF V_EXISTE = 0 THEN
            RAISE_APPLICATION_ERROR(PKG_MINDCARE_COMUM.C_ERR_CLINICA_NAO_ENCONTRADA, 'Clínica não existente.');
        END IF;
    END PRC_VALIDAR_CLINICA;

    -- Garante que a clínica existe e devolve a taxa de comissão (0 quando nula).
    FUNCTION FN_TAXA_COMISSAO (P_CLINICA_ID IN CLINICA.ID%TYPE) RETURN NUMBER IS
        V_TAXA CLINICA.TAXA_COMISSAO%TYPE;
    BEGIN
        SELECT NVL(TAXA_COMISSAO, 0)
          INTO V_TAXA
          FROM CLINICA
         WHERE ID = P_CLINICA_ID;
        RETURN V_TAXA;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(PKG_MINDCARE_COMUM.C_ERR_CLINICA_NAO_ENCONTRADA, 'Clínica não existente.');
    END FN_TAXA_COMISSAO;

    FUNCTION FN_ID_CLINICA (P_CNPJ IN CLINICA.CNPJ%TYPE) RETURN CLINICA.ID%TYPE IS
        V_ID CLINICA.ID%TYPE;
    BEGIN
        SELECT ID INTO V_ID FROM CLINICA WHERE CNPJ = P_CNPJ;
        RETURN V_ID;
    EXCEPTION
        WHEN NO_DATA_FOUND THEN
            RAISE_APPLICATION_ERROR(PKG_MINDCARE_COMUM.C_ERR_CLINICA_NAO_ENCONTRADA, 'Clínica não existente.');
    END FN_ID_CLINICA;

    FUNCTION FN_FATURAMENTO_MES (
        P_CLINICA_ID IN CLINICA.ID%TYPE,
        P_ANO        IN PLS_INTEGER,
        P_MES        IN PLS_INTEGER
    ) RETURN NUMBER
    IS
        V_INICIO DATE := PKG_MINDCARE_COMUM.FN_INICIO_MES(P_ANO, P_MES);
        V_TOTAL  NUMBER;
    BEGIN
        PRC_VALIDAR_CLINICA(P_CLINICA_ID);

        SELECT NVL(SUM(VALOR_CONSULTA), 0)
          INTO V_TOTAL
          FROM CONSULTA
         WHERE CLINICA_ID = P_CLINICA_ID
           AND ATENDIDA = 1
           AND CANCELADA = 0
           AND DATA_HORA_CONSULTA >= V_INICIO
           AND DATA_HORA_CONSULTA <  ADD_MONTHS(V_INICIO, 1);
        RETURN V_TOTAL;
    END FN_FATURAMENTO_MES;

    FUNCTION FN_FATURAMENTO_MES (
        P_CNPJ IN CLINICA.CNPJ%TYPE,
        P_ANO  IN PLS_INTEGER,
        P_MES  IN PLS_INTEGER
    ) RETURN NUMBER
    IS
    BEGIN
        RETURN FN_FATURAMENTO_MES(FN_ID_CLINICA(P_CNPJ), P_ANO, P_MES);
    END FN_FATURAMENTO_MES;

    FUNCTION FN_RECEITA_LIQUIDA_MES (
        P_CLINICA_ID IN CLINICA.ID%TYPE,
        P_ANO        IN PLS_INTEGER,
        P_MES        IN PLS_INTEGER
    ) RETURN NUMBER
    IS
    BEGIN
        RETURN ROUND(FN_FATURAMENTO_MES(P_CLINICA_ID, P_ANO, P_MES) * (1 - FN_TAXA_COMISSAO(P_CLINICA_ID)), 2);
    END FN_RECEITA_LIQUIDA_MES;

    FUNCTION FN_RECEITA_LIQUIDA_MES (
        P_CNPJ IN CLINICA.CNPJ%TYPE,
        P_ANO  IN PLS_INTEGER,
        P_MES  IN PLS_INTEGER
    ) RETURN NUMBER
    IS
    BEGIN
        RETURN FN_RECEITA_LIQUIDA_MES(FN_ID_CLINICA(P_CNPJ), P_ANO, P_MES);
    END FN_RECEITA_LIQUIDA_MES;

    PROCEDURE PRC_RESUMO_DASHBOARD (
        P_CLINICA_ID            IN  CLINICA.ID%TYPE,
        P_ANO                   IN  PLS_INTEGER,
        P_MES                   IN  PLS_INTEGER,
        P_TOTAL_PACIENTES       OUT PLS_INTEGER,
        P_TOTAL_PROFISSIONAIS   OUT PLS_INTEGER,
        P_PACIENTES_ATENCAO     OUT PLS_INTEGER,
        P_CONSULTAS_AGENDADAS   OUT PLS_INTEGER,
        P_CONSULTAS_ATENDIDAS   OUT PLS_INTEGER,
        P_CONSULTAS_CANCELADAS  OUT PLS_INTEGER,
        P_TAXA_CANCELAMENTO     OUT NUMBER,
        P_FATURAMENTO           OUT NUMBER,
        P_RECEITA_LIQUIDA       OUT NUMBER
    )
    IS
        V_INICIO DATE := PKG_MINDCARE_COMUM.FN_INICIO_MES(P_ANO, P_MES);
        V_TOTAL  PLS_INTEGER;
    BEGIN
        P_FATURAMENTO := FN_FATURAMENTO_MES(P_CLINICA_ID, P_ANO, P_MES);
        P_RECEITA_LIQUIDA := ROUND(P_FATURAMENTO * (1 - FN_TAXA_COMISSAO(P_CLINICA_ID)), 2);

        SELECT COUNT(CASE WHEN DTYPE = 'Paciente' THEN 1 END),
               COUNT(CASE WHEN DTYPE = 'Profissional' THEN 1 END),
               COUNT(CASE WHEN DTYPE = 'Paciente' AND ESTADO_PACIENTE = 'ATENCAO' THEN 1 END)
          INTO P_TOTAL_PACIENTES, P_TOTAL_PROFISSIONAIS, P_PACIENTES_ATENCAO
          FROM USUARIO
         WHERE CLINICA_ID = P_CLINICA_ID
           AND ENCERRADA_EM IS NULL;

        SELECT COUNT(*),
               COUNT(CASE WHEN ATENDIDA = 1 THEN 1 END),
               COUNT(CASE WHEN CANCELADA = 1 THEN 1 END)
          INTO V_TOTAL, P_CONSULTAS_ATENDIDAS, P_CONSULTAS_CANCELADAS
          FROM CONSULTA
         WHERE CLINICA_ID = P_CLINICA_ID
           AND DATA_HORA_CONSULTA >= V_INICIO
           AND DATA_HORA_CONSULTA <  ADD_MONTHS(V_INICIO, 1);

        P_CONSULTAS_AGENDADAS := V_TOTAL - P_CONSULTAS_CANCELADAS;
        P_TAXA_CANCELAMENTO := CASE WHEN V_TOTAL = 0 THEN 0
                                    ELSE ROUND(P_CONSULTAS_CANCELADAS * 100 / V_TOTAL, 2) END;
    END PRC_RESUMO_DASHBOARD;

    FUNCTION FN_AGENDA_CLINICA (
        P_CLINICA_ID IN CLINICA.ID%TYPE,
        P_INICIO     IN DATE,
        P_FIM        IN DATE
    ) RETURN SYS_REFCURSOR
    IS
        V_RESULTADO SYS_REFCURSOR;
    BEGIN
        IF P_INICIO IS NULL OR P_FIM IS NULL OR P_FIM < P_INICIO THEN
            RAISE_APPLICATION_ERROR(PKG_MINDCARE_COMUM.C_ERR_PARAMETRO_INVALIDO, 'Período inválido.');
        END IF;
        PRC_VALIDAR_CLINICA(P_CLINICA_ID);

        OPEN V_RESULTADO FOR
            SELECT C.NUMERO,
                   C.DATA_HORA_CONSULTA,
                   C.CONSULTA_MODALIDADE,
                   C.VALOR_CONSULTA,
                   C.ATENDIDA,
                   C.CANCELADA,
                   PAC.NOME_COMPLETO  AS PACIENTE,
                   PRO.NOME_COMPLETO  AS PROFISSIONAL,
                   PRO.TIPO_PROFISSIONAL
              FROM CONSULTA C
              JOIN USUARIO PAC ON PAC.ID = C.PACIENTE_ID
              JOIN USUARIO PRO ON PRO.ID = C.PROFISSIONAL_ID
             WHERE C.CLINICA_ID = P_CLINICA_ID
               AND C.DATA_HORA_CONSULTA >= TRUNC(P_INICIO)
               AND C.DATA_HORA_CONSULTA <  TRUNC(P_FIM) + 1
             ORDER BY C.DATA_HORA_CONSULTA, PRO.NOME_COMPLETO;

        RETURN V_RESULTADO;
    END FN_AGENDA_CLINICA;

END PKG_MINDCARE_CLINICA;
